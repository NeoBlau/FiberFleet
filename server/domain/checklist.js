export const ITEMS = Object.fromEntries(
  SECTIONS.flatMap((s) => s.items.map((i) => [i.id, { ...i, section: s.id, vehicle: i.vehicle || s.vehicle || 'any' }])),
);

// Позиции на схеме осей. code: "<veh>:<axle>:<side>", side: L|R
export function axlePositions(vehType, axles) {
  const out = [];
  for (let a = 1; a <= axles; a++) {
    for (const side of ['L', 'R']) out.push({ code: `${vehType}:${a}:${side}`, vehType, axle: a, side });
  }
  return out;
}

export function positionLabel(code) {
  const [veh, axle, side] = String(code).split(':');
  const v = veh === 'tractor' ? 'Тягач' : 'Прицеп';
  const s = side === 'L' ? 'лев.' : side === 'R' ? 'прав.' : '';
  return `${v}, ось ${axle}${s ? ', ' + s : ''}`;
}

export function parsePosition(code) {
  const [veh, axle, side] = String(code).split(':');
  return { veh, axle: Number(axle), side };
}

// Все ссылки на справочник работ, используемые правилами (для проверки целостности)
export function referencedWorkKeys() {
  const keys = new Set();
  for (const item of Object.values(ITEMS)) {
    for (const w of item.works || []) keys.add(w.wt);
    for (const r of item.related || []) keys.add(r.wt);
    for (const o of item.options || []) keys.add(o);
  }
  return [...keys];
}

