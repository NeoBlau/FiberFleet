// Шаблон дефектной ведомости (по форме «Дефектная ведомость» заказчика) и база правил:
// дефект → работы из справочника → зона осмотра (куда залезть, что проверить) → связанные проверки.
//
// Виды пунктов:
//   pm        — норма / дефект («+/-» в бумажной ведомости)
//   yesno     — есть / нет дефектов (дефект = «есть»)
//   volt      — замер напряжения, дефект если вне диапазона [min, max]
//   mileage   — работа «по пробегу», статус считается по правилам ТО (ключ maint)
//   positions — отметка позиций на схеме осей (тягач/прицеп × ось × сторона)
//   damage    — фиксация новых повреждений (выделить цветом), работ не создаёт
//
// Работы задаются ссылкой "Категория::Название" на справочник. Фильтры подбора:
//   veh: tractor|trailer, axle: front|rear, brake: disc|drum.
// Приоритет: 1 — критично (безопасность, выпуск запрещён), 2 — высокий, 3 — плановый, 4 — по согласованию.
// seq: 0 — мойка, 1 — осмотр/диагностика, 2 — ремонт, 3 — регулировки после ремонта. Внутри ремонта по одному ТС
// задачи с меньшим seq выполняются раньше.

