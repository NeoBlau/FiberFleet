// ---------- helpers ----------
function runs(text, opts = {}) {
  return String(text).split(/(\[[^\]]+\])/).filter(Boolean).map((t) => new TextRun({
    text: t, font: FONT, size: opts.size || 24, bold: opts.bold, italics: opts.italics,
    ...(t.startsWith('[') ? { shading: { type: ShadingType.CLEAR, fill: 'FFF2A8', color: 'auto' } } : {}),
  }));
}
const P = (text, o = {}) => new Paragraph({
  children: runs(text, o), alignment: o.align || AlignmentType.JUSTIFIED,
  spacing: { after: o.after ?? 120, before: o.before ?? 0, line: o.line || 300 }, indent: o.indent ? { firstLine: 567 } : undefined,
  keepNext: o.keepNext,
});
const H = (text, level = HeadingLevel.HEADING_1, align = AlignmentType.CENTER) => new Paragraph({
  heading: level, alignment: align, spacing: { before: 200, after: 160 },
  children: [new TextRun({ text, font: FONT, bold: true, size: level === HeadingLevel.HEADING_1 ? 28 : 24 })],
});
const B = (text, o = {}) => new Paragraph({ numbering: { reference: 'bul', level: 0 }, children: runs(text, o), spacing: { after: 80, line: 280 }, alignment: AlignmentType.JUSTIFIED });
const N = (text, ref = 'num') => new Paragraph({ numbering: { reference: ref, level: 0 }, children: runs(text), spacing: { after: 100, line: 280 }, alignment: AlignmentType.JUSTIFIED });
const SP = () => new Paragraph({ children: [], spacing: { after: 120 } });

const border = { style: BorderStyle.SINGLE, size: 4, color: '808080' };
const borders = { top: border, bottom: border, left: border, right: border };
function table(rows, widths = [3400, W - 3400], header = false) {
  return new Table({
    width: { size: W, type: WidthType.DXA }, columnWidths: widths,
    rows: rows.map((r, ri) => new TableRow({
      tableHeader: header && ri === 0,
      children: r.map((c, ci) => new TableCell({
        width: { size: widths[ci], type: WidthType.DXA }, borders,
        margins: { top: 60, bottom: 60, left: 100, right: 100 },
        shading: (header && ri === 0) || (!header && ci === 0) ? { type: ShadingType.CLEAR, fill: 'EEF2F6', color: 'auto' } : undefined,
        children: String(c).split('\n').map((line) => new Paragraph({ children: runs(line, { size: 22, bold: header && ri === 0 }), spacing: { after: 40 } })),
      })),
    })),
  });
}
const sign = (who) => table([[who, '_______________ / [Фамилия И.О.]'], ['Дата', '«___» ____________ 20__ г.']], [4200, W - 4200]);

function save(name, children, { footer = true } = {}) {
  const doc = new Document({
    creator: 'FiberFleet',
    styles: { default: { document: { run: { font: FONT, size: 24 } } } },
    numbering: {
      config: [
        { reference: 'bul', levels: [{ level: 0, format: LevelFormat.BULLET, text: '–', alignment: AlignmentType.LEFT, style: { paragraph: { indent: { left: 567, hanging: 283 } } } }] },
        ...['num', 'num2', 'num3', 'num4', 'num5', 'num6'].map((reference) => ({
          reference, levels: [{ level: 0, format: LevelFormat.DECIMAL, text: '%1.', alignment: AlignmentType.LEFT, style: { paragraph: { indent: { left: 567, hanging: 397 } } } }],
        })),
      ],
    },
    sections: [{
      properties: { page: { size: { width: 11906, height: 16838 }, margin: { top: 1134, bottom: 1134, left: 1418, right: 850 } } },
      footers: footer ? { default: new Footer({ children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ children: [PageNumber.CURRENT], font: FONT, size: 20 })] })] }) } : undefined,
      children,
    }],
  });
  return Packer.toBuffer(doc).then((buf) => { fs.writeFileSync(path.join(OUT, name), buf); console.log('✓', name); });
}

